// Writes COPY_REVIEW.md from src/content.js so the review sheet always matches
// what ships. Run after editing copy:
//
//   npm run copy-review
//
// The generator test fails if COPY_REVIEW.md is out of date.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONTENT } from '../src/content.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const words = (s) => s.trim().split(/\s+/).length;
const box = (s) => `- [ ] ${s}`;
const q = (s) => `"${s}"`;

export function buildCopyReview() {
  const C = CONTENT;
  const out = [];
  const add = (...lines) => out.push(...lines);

  add(
    '# Copy review',
    '',
    'Every feature claim, tagline, tip and link in Otter Crossing, in one place. Check each line against help.otter.ai, tick the box, and send back anything to change. All of it lives in `src/content.js`.',
    '',
    'This file is generated from `src/content.js` by `npm run copy-review`. Edit the copy there, then regenerate this file. Do not edit this file by hand.',
    '',
    'Everything below is marked draft in the code until you sign off.',
    '',
    '## Flagged for a closer look',
    '',
    'These lines say a little more than the taglines, or depend on product details I could not confirm. Each one is a judgment call for you or PMM.',
    '',
    box('**Live Assist** copy is new and based on the draft GTM Enablement Hub in Notion, which says positioning is not final. Live Assist is live for Enterprise only. It is now switched on and shows in every run, so confirm the tagline with PMM. There is no help center article yet, so the link is the launch how-to blog post.'),
    box('**Work Mode** is switched on ahead of its October 15 external launch, at your request. The copy follows the help center and the Notion naming decision. Free users see Work Mode locked in the product, so an external audience may need a "Pro and Business" note. The game over line "Your Work run had {n} of {total} lanes left" is game copy, not a product claim.'),
    box('**Action Items casing.** The help center calls the feature "Action Items," so the feature name now uses that casing. Generic counts in the game UI (the HUD and game over stats) stay sentence case.'),
    box('**Try Otter link** has no campaign tracking. Add UTM parameters if marketing wants booth and webinar traffic attributed.'),
    box('**Booth consent text and privacy link** are placeholders for Legal (`booth.consent`, `booth.privacyUrl`). They only show when `BOOTH_MODE` is true.'),
    box('**One brand blue.** Everything blue in the game (logo, buttons, signs, glows, pickups) is #144FFF, the logo blue in the otter.ai media kit (blue-horizontal.svg). The river is its own water blue. The logo mark itself comes from the otter.ai site header. Confirm usage with brand before launch.'),
    '',
  );

  const WHERE = {
    notetaker: 'pickup card (name, tagline), river (name, tagline), recap (name, description, link)',
    aiChat: 'pickup card (name, tagline), river (name, tagline), recap (name, description, link)',
    summary: 'pickup card (name, tagline), river (name, tagline), recap (name, description, link)',
    actionItems: 'pickup card (name, tagline), river (name, tagline), recap (name, description, link)',
    highlights: 'river (name, tagline), recap after riding a log (name, description, link)',
    liveAssist: 'pickup card (name, tagline), river (name, tagline), recap (name, description, link)',
    workMode: 'pickup card (name, tagline), river (name, tagline), recap (name, description, link), game over line when a run was cut short',
  };
  add(
    '## Validation, October 12, 2026',
    '',
    'Each feature claim was checked against the help center article linked under it and against internal Notion docs. Changes made in this pass:',
    '',
    '- Help links now point to the specific article for each feature instead of the help center home page.',
    '- Summary tagline: "without rewatching" is now "without listening back." Otter is audio first, and the onboarding script in Notion says "without listening back to the whole thing."',
    '- Otter Notetaker tip: "could have taken that meeting for you" is now "could have joined that meeting for you." The help center says you can send Notetaker to a meeting you cannot attend.',
    '- Deadline Hawk tip: "make follow-up fast" is now "save time on follow-up." The Meeting Summary article says the summary saves time after a meeting.',
    '- Live Assist placeholder copy is replaced. It shipped to Enterprise on July 21, 2026 (Notion roadmap card and GTM hub).',
    '',
  );
  const SOURCES = {
    workMode: 'Otter AI Chat Overview V2 (help center): "Switch to Work when you want Otter to complete tasks for you, such as creating Jira tickets, adding pages to Notion, creating files in Google Drive, or drafting emails in Gmail." Notion: Naming Decision: Work Mode ("hand it to Work"), Chat: Work Mode PRD ("hand Otter the whole task"), GTM Enablement Hub (external launch October 15, first prompt to try is the follow-up email).',
    notetaker: 'Otter Notetaker Overview (help center): joins Zoom, Google Meet and Microsoft Teams meetings and takes notes, including meetings you cannot attend.',
    aiChat: 'Otter AI Chat Overview and AI Chat FAQs (help center): ask questions "anytime during the live meeting or post-meeting." On by default for all accounts. Notion onboarding script uses "I missed the last half, catch me up?"',
    summary: 'Meeting Summary Overview (help center): a quick overview of topics, action items and highlights that saves time after a meeting. Notion onboarding script: next steps "without listening back to the whole thing."',
    actionItems: 'Action Items Overview (help center): action items are assigned to people and can be reassigned. Notion onboarding script: Otter automatically generates Action Items.',
    highlights: 'Add highlights to your conversation (help center): highlight during the live recording or after.',
    liveAssist: 'Notion: Live Assist roadmap card (GA July 21, 2026) and the Live Assist + Agent Builder GTM Enablement Hub (draft): private tip cards such as the next question to ask, visible only to the person being coached, Enterprise only.',
  };
  add('## 1. Feature claims', '');
  for (const [id, f] of Object.entries(C.features)) {
    add(`### ${f.name}${f.placeholder ? ' (placeholder)' : f.unreleased ? ' (behind SHOW_UNRELEASED)' : ''}`, '');
    if (WHERE[id]) add(`Appears on: ${WHERE[id]}.`, '');
    if (SOURCES[id]) add(`Checked against: ${SOURCES[id]}`, '');
    add(box(`Name: ${q(f.name)}`));
    add(box(`Tagline (${words(f.tagline)} words, max 6): ${q(f.tagline)}`));
    add(box(`Description: ${q(f.description)}`));
    add(box(`Help link: ${f.helpUrl}`));
    add(`- Key in content.js: \`features.${id}\``, '');
  }

  add('## 2. Game over causes and tips', '', 'The cause is the big heading on the game over screen. The tip below it names the feature that would have helped.', '');
  for (const [id, d] of Object.entries(C.deaths)) {
    add(box(`${q(d.title)}: ${q(d.tip)} (\`deaths.${id}\`)`));
  }
  add('');

  add('## 3. Power-up messages', '', 'Shown for a moment when a power-up does its job.', '');
  for (const [id, m] of Object.entries(C.powerupMessages)) {
    if (id === 'draft') continue;
    add(box(`${q(m)} (\`powerupMessages.${id}\`)`));
  }
  add('');

  add('## 4. The river', '', 'No text on the water or the logs.', '');
  add('');

  add('## 5. Lane hints', '', 'Shown once, the first time each lane type appears in a run.', '');
  for (const [id, h] of Object.entries(C.hints)) {
    if (id === 'draft') continue;
    add(box(`${q(h)} (\`hints.${id}\`)`));
  }
  add('');

  add('## 6. How to play', '');
  for (const l of C.howTo.lines) add(box(q(l)));
  add('');

  add('## 7. Meeting titles', '', 'Drawn on the meeting blocks. All fictional. Internal titles only show when `AUDIENCE` is `"internal"`.', '');
  for (const aud of ['external', 'internal']) {
    add(`### ${aud === 'external' ? 'External (default)' : 'Internal'}`, '');
    for (const len of [1, 2, 3]) {
      add(box(`${len * 30} minutes: ${C.meetingTitles[aud][len].map(q).join(', ')}`));
    }
    add('');
  }

  add('## 8. Links', '');
  add(box(`${q(C.links.tryOtter.label)} button: ${C.links.tryOtter.url} (external mode only)`));
  add('');

  add('## 9. Daily challenge and outfits', '');
  add(box(`Daily tag: ${q(C.daily.tag)}`));
  add(box(`Slack share text: ${q(C.daily.share)}`));
  add(box(`Copy messages: ${q(C.daily.copyResult)}, ${q(C.daily.copied)}, ${q(C.daily.copyManual)}`));
  for (const [id, o] of Object.entries(C.outfits.items)) add(box(`Outfit ${q(o.name)}: ${q(o.line)} (\`outfits.items.${id}\`)`));
  add(box(['heading', 'walletLabel', 'wear', 'wearing', 'buy', 'need'].map((k) => q(C.outfits[k])).join(', ')));
  add('');

  add('## 10. Booth mode', '', 'Only shown when `BOOTH_MODE` is true. The sign-up box is unchecked by default and sign-ups are stored on the device only.', '');
  add(box(`Heading: ${q(C.booth.emailHeading)}, field: ${q(C.booth.emailLabel)}`));
  add(box(`Consent (Legal): ${q(C.booth.consent)}`));
  add(box(`Privacy link (Legal): ${q(C.booth.privacyLabel)} ${C.booth.privacyUrl}`));
  add(box(['submit', 'thanks', 'invalid', 'needConsent'].map((k) => q(C.booth[k])).join(', ')));
  add(box(`Staff admin screen: ${Object.values(C.admin).map(q).join(', ')}`));
  add(box(`Online boards (live only when Supabase is configured; check with legal: the company board stores the email domain): ${Object.values(C.online).map(q).join(', ')}`));
  add('');

  add('## 11. Screen labels', '', 'Low risk, listed for completeness.', '');
  add(box(`Title sign: ${q(C.game.title)}, tag: ${q(C.game.signTag)}`));
  const skip = new Set(['title', 'signTag']);
  const labels = Object.entries(C.game).filter(([k]) => !skip.has(k)).flatMap(([, v]) => (typeof v === 'string' ? [q(v)] : Object.values(v).map(q)));
  add(box(labels.join(', ')));
  add(box(`Train label: ${q(C.labels.allHandsTrain)}`));
  add('');

  return out.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'COPY_REVIEW.md'), buildCopyReview());
  console.log('Wrote COPY_REVIEW.md');
}
